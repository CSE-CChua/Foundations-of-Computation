#!/usr/bin/env python3
"""
CSCE 355 - JFLAP5 (pushdown automata) grader
=============================================

Run from inside your assignment folder:

    python3 test_pda.py              # grade all five problems
    python3 test_pda.py 2            # grade only Problem 2
    python3 test_pda.py --selfcheck  # (instructors) verify the target languages and test files

For every problem the script:

  1. Parses the .jff file. It must be a JFLAP *Pushdown Automaton*.
  2. Checks the form of the machine, before running any test string:
       - exactly one initial state;
       - every transition's input label uses only symbols of the problem's
         alphabet (it may read several symbols, since you build the PDA with
         "Multiple Character Input", or none: lambda). A label such as "a,b" is
         read by JFLAP as the 3-character string "a,b", so it is not allowed:
         draw one transition per choice.
  3. Runs the machine the way JFLAP does: nondeterministically, starting with
     Z alone on the stack, ACCEPTING BY FINAL STATE (all input read and the
     machine in a final state; the stack may hold anything).
  4. Checks the strings in the provided *_tests.txt file (first 5 reject,
     last 5 accept) and the empty string.
  5. Checks EVERY string up to a fixed length (see CHECK_LENGTH), plus some
     longer strings, against the described language. (Whether two PDAs accept
     the same language cannot be decided by any program, so this is a bounded
     check, but a thorough one.) If your PDA is wrong it prints a shortest
     string on which it is wrong.

A problem earns its points only if all of these pass.

Do not edit this file or the *_tests.txt files: the graders replace them with
the master copies before grading (see gradeall.py).
"""

import itertools
import os
import sys
import xml.etree.ElementTree as ET
from collections import deque

# ---------------------------------------------------------------------------
# Grader settings (instructors may change these)
# ---------------------------------------------------------------------------
CHECK_LENGTH = {"ab": 10, "abc": 7, "01": 12}   # all strings up to this length are checked
SHOW_COUNTEREXAMPLE = True  # print a shortest string on which the machine is wrong
STACK_SLACK = 12            # simulation keeps stacks up to 3*len(input) + STACK_SLACK symbols
CONFIG_BUDGET = 100000      # per string: give up (and count as reject) after this many configurations
PROBLEM_BUDGET = 3000000    # per problem: stop the check after this many configurations in total

MAX_DISPLAY = 60
MAX_LISTED = 10
BOTTOM = "Z"


# ---------------------------------------------------------------------------
# Target languages
# ---------------------------------------------------------------------------
def runs(s, letters):
    """If s is letters[0]^n0 letters[1]^n1 ..., return [n0, n1, ...]; else None."""
    counts, i = [], 0
    for ch in letters:
        j = i
        while j < len(s) and s[j] == ch:
            j += 1
        counts.append(j - i)
        i = j
    return counts if i == len(s) else None


def p1(s):          # a^x b^y c^x
    r = runs(s, "abc")
    return r is not None and r[0] == r[2]


def p2(s):          # not of the form ww
    n = len(s)
    return n % 2 == 1 or s[:n // 2] != s[n // 2:]


def p3(s):          # 0^n 1^n  or  0^n 1^2n,  n >= 1
    r = runs(s, "01")
    return r is not None and r[0] >= 1 and r[1] in (r[0], 2 * r[0])


def p4(s):          # a^i b^j c^k with j = i + k
    r = runs(s, "abc")
    return r is not None and r[1] == r[0] + r[2]


def p5(s):          # a^n b^m with n <= m <= 2n
    r = runs(s, "ab")
    return r is not None and r[0] <= r[1] <= 2 * r[0]


def long_strings(num):
    """Longer members and near-misses, beyond the exhaustive length."""
    A = lambda ch, n: ch * n
    if num == 1:
        return [A("a", 9) + A("b", 4) + A("c", 9), A("a", 9) + A("b", 4) + A("c", 8),
                A("a", 9) + A("c", 10), A("b", 15), A("a", 10) + A("c", 10) + "a"]
    if num == 2:
        w = "abbabaabbab"
        return [w + w, w + w[:-1] + "a", w + "b" + w, "ab" * 7, "ab" * 6 + "ba"]
    if num == 3:
        return [A("0", 8) + A("1", 8), A("0", 8) + A("1", 16), A("0", 8) + A("1", 12),
                A("0", 8) + A("1", 15), A("0", 8) + A("1", 17), A("0", 8) + A("1", 7)]
    if num == 4:
        return [A("a", 6) + A("b", 10) + A("c", 4), A("a", 6) + A("b", 9) + A("c", 4),
                A("a", 6) + A("b", 11) + A("c", 4), A("b", 12) + A("c", 12), A("a", 12) + A("b", 12)]
    if num == 5:
        return [A("a", 8) + A("b", m) for m in (7, 8, 12, 16, 17)] + [A("a", 8) + A("b", 12) + "a"]
    return []


# ---------------------------------------------------------------------------
# The five problems.  Every test file: the first 5 lines reject, the last 5 accept.
# ---------------------------------------------------------------------------
PROBLEMS = [
    dict(num=1, title="a^x b^y c^x", points=10, alphabet="abc", pred=p1,
         jff="problem1_axbycx.jff", tests="problem1_axbycx_tests.txt"),
    dict(num=2, title="strings over {a,b} that are not of the form ww", points=20, alphabet="ab", pred=p2,
         jff="problem2_not_ww.jff", tests="problem2_not_ww_tests.txt"),
    dict(num=3, title="0^n 1^n  or  0^n 1^2n  (n >= 1)", points=10, alphabet="01", pred=p3,
         jff="problem3_0n1n_or_0n12n.jff", tests="problem3_0n1n_or_0n12n_tests.txt"),
    dict(num=4, title="a^i b^j c^k with j = i + k", points=5, alphabet="abc", pred=p4,
         jff="problem4_aibjck.jff", tests="problem4_aibjck_tests.txt"),
    dict(num=5, title="a^n b^m with n <= m <= 2n", points=5, alphabet="ab", pred=p5,
         jff="problem5_anbm.jff", tests="problem5_anbm_tests.txt"),
]
TOTAL_POSSIBLE = sum(p["points"] for p in PROBLEMS)   # 50
SPLIT = [("reject", 5), ("accept", 5)]


def fmt(x):
    return ("%.2f" % x).rstrip("0").rstrip(".")


# ---------------------------------------------------------------------------
# Reading the .jff file
# ---------------------------------------------------------------------------
class JFFError(Exception):
    pass


LAMBDA_TEXT = ("", "λ", "ε")


def parse_jff(path):
    if not os.path.exists(path):
        raise JFFError("file not found: %s" % path)
    try:
        root = ET.parse(path).getroot()
    except ET.ParseError as e:
        raise JFFError("the file is not valid JFLAP XML (%s)" % e)
    kind = (root.findtext("type") or "").strip()
    if kind != "pda":
        raise JFFError("this file holds a '%s' machine, but this assignment needs a Pushdown Automaton "
                       "(in JFLAP choose 'Pushdown Automaton', then 'Multiple Character Input')"
                       % (kind or "unknown"))
    aut = root.find("automaton")
    if aut is None:
        raise JFFError("no <automaton> element found")
    states, initial, finals = {}, [], set()
    for s in aut.findall("state"):
        sid = s.get("id")
        states[sid] = s.get("name") or ("q" + str(sid))
        if s.find("initial") is not None:
            initial.append(sid)
        if s.find("final") is not None:
            finals.add(sid)

    def txt(t, tag):
        e = t.find(tag)
        return "" if (e is None or e.text is None) else e.text

    edges = []
    for t in aut.findall("transition"):
        edges.append(((t.findtext("from") or "").strip(), (t.findtext("to") or "").strip(),
                      txt(t, "read"), txt(t, "pop"), txt(t, "push")))
    return dict(states=states, initial=initial, finals=finals, edges=edges)


def check_pda(fa, prob):
    states = fa["states"]
    name = lambda sid: states.get(sid, "?")
    if not states:
        raise JFFError("the file contains no states: it is still the empty template")
    if not fa["initial"]:
        raise JFFError("no initial state is set (right-click a state and choose 'Initial')")
    problems = []
    if len(fa["initial"]) > 1:
        problems.append("more than one initial state (%s)" % ", ".join(name(i) for i in fa["initial"]))
    if not fa["finals"]:
        problems.append("no final state: this assignment accepts by final state, so the PDA accepts nothing")
    edges = []
    for frm, to, read, pop, push in fa["edges"]:
        if frm not in states or to not in states:
            problems.append("a transition refers to a state that does not exist")
            continue
        where = "transition %s -> %s (%s, %s; %s)" % (name(frm), name(to), read or "λ", pop or "λ",
                                                    push or "λ")
        r = "" if read.strip() in LAMBDA_TEXT else read.strip()
        po = "" if pop.strip() in LAMBDA_TEXT else pop.strip()
        pu = "" if push.strip() in LAMBDA_TEXT else push.strip()
        bad = sorted(set(ch for ch in r if ch not in prob["alphabet"]))
        if bad:
            if "," in bad or " " in bad:
                problems.append("%s: the input label '%s' contains a comma or space. JFLAP reads it as that "
                                "exact string, not as a list of choices: draw a separate transition for "
                                "each choice" % (where, r))
            else:
                problems.append("%s reads '%s', which is not in the alphabet {%s}"
                                % (where, "".join(bad), ", ".join(prob["alphabet"])))
            continue
        if any(c.isspace() for c in po + pu):
            problems.append("%s: stack labels may not contain spaces" % where)
            continue
        edges.append((frm, to, r, po, pu))
    out = dict(edges=edges, initial=fa["initial"][0], finals=fa["finals"], n_states=len(states),
               n_edges=len(edges), n_lambda=sum(1 for e in edges if e[2] == ""))
    return out, problems


# ---------------------------------------------------------------------------
# Simulation: nondeterministic, accept by final state, Z starts on the stack
# ---------------------------------------------------------------------------
class Result(object):
    __slots__ = ("accept", "truncated", "work")

    def __init__(self, accept, truncated, work=0):
        self.accept, self.truncated, self.work = accept, truncated, work


def simulate(pda, w):
    """Breadth-first search over configurations (state, position, stack) with the top of the
    stack first. Stacks taller than 3*len(w)+STACK_SLACK are cut off (that only matters for a
    PDA that keeps pushing on lambda moves). Returns Result(accept, truncated)."""
    by_state = {}
    for frm, to, r, po, pu in pda["edges"]:
        by_state.setdefault(frm, []).append((to, r, po, pu))
    limit = 3 * len(w) + STACK_SLACK
    start = (pda["initial"], 0, BOTTOM)
    seen, queue, truncated = {start}, deque([start]), False
    while queue:
        q, i, st = queue.popleft()
        if i == len(w) and q in pda["finals"]:
            return Result(True, truncated, len(seen))
        for to, r, po, pu in by_state.get(q, ()):
            if r and not w.startswith(r, i):
                continue
            if po and not st.startswith(po):
                continue
            ns = pu + st[len(po):]
            if len(ns) > limit:
                truncated = True
                continue
            c = (to, i + len(r), ns)
            if c not in seen:
                if len(seen) >= CONFIG_BUDGET:
                    return Result(False, True, len(seen))
                seen.add(c)
                queue.append(c)
    return Result(False, truncated, len(seen))


# ---------------------------------------------------------------------------
# Grading
# ---------------------------------------------------------------------------
def show(s):
    if s == "":
        return "(empty string)"
    return s if len(s) <= MAX_DISPLAY else "%s... (length %d)" % (s[:MAX_DISPLAY], len(s))


def load_tests(path):
    if not os.path.exists(path):
        raise JFFError("test file not found: %s" % path)
    with open(path, encoding="utf-8", errors="replace", newline=None) as f:
        lines = f.read().split("\n")
    while lines and lines[-1] == "":
        lines.pop()
    return lines


def expected_labels(n):
    labels = [lab for lab, c in SPLIT for _ in range(c)]
    if len(labels) != n:
        raise JFFError("test data error: expected %d test lines but found %d" % (len(labels), n))
    return labels


def all_strings(alphabet, max_len):
    for length in range(max_len + 1):
        for tup in itertools.product(alphabet, repeat=length):
            yield "".join(tup)


def grade_problem(prob):
    pts = prob["points"]
    print("\n" + "-" * 60)
    print("Problem %d: %s  (%s points)" % (prob["num"], prob["title"], fmt(pts)))
    print("-" * 60)
    print("  File: %s" % prob["jff"])
    try:
        fa = parse_jff(prob["jff"])
        pda, problems = check_pda(fa, prob)
    except JFFError as e:
        print("  [FAIL] %s" % e)
        print("  Score: 0 / %s" % fmt(pts))
        return 0
    if problems:
        print("  [FAIL] The machine does not have the required form, so it earns no credit:")
        for p in problems:
            print("    - %s" % p)
        print("  Score: 0 / %s" % fmt(pts))
        return 0
    print("  Form check passed: %d states, %d transitions (%d read lambda)."
          % (pda["n_states"], pda["n_edges"], pda["n_lambda"]))

    fails, truncated_any = [], False
    try:
        lines = load_tests(prob["tests"])
        labels = expected_labels(len(lines))
    except JFFError as e:
        print("  [FAIL] %s" % e)
        print("  Score: 0 / %s" % fmt(pts))
        return 0
    wrong, exhausted = [], False
    for i, (s, want) in enumerate(zip(lines, labels), 1):
        res = simulate(pda, s)
        truncated_any |= res.truncated
        exhausted |= res.work >= CONFIG_BUDGET
        got = "accept" if res.accept else "reject"
        if got != want:
            wrong.append("line %d: %s -> expected %s, your PDA %ss" % (i, show(s), want.upper(), got))
    if wrong:
        fails.append("%d of %d provided test strings are wrong:" % (len(wrong), len(lines)))
        fails += ["    " + x for x in wrong[:MAX_LISTED]]
    else:
        print("  Provided tests: all %d strings correct." % len(lines))

    want_e = prob["pred"]("")
    res = simulate(pda, "")
    exhausted |= res.work >= CONFIG_BUDGET
    if res.accept == want_e:
        print("  Empty string: %s, as required." % ("accepted" if want_e else "rejected"))
    else:
        fails.append("the empty string must be %s, but your PDA %s it"
                     % ("accepted" if want_e else "rejected", "accepts" if res.accept else "rejects"))

    max_len = CHECK_LENGTH[prob["alphabet"]]
    checked, first_bad = 0, None
    candidates = itertools.chain(all_strings(prob["alphabet"], max_len), long_strings(prob["num"]))
    work, gave_up = 0, False
    for s in candidates:
        checked += 1
        res = simulate(pda, s)
        truncated_any |= res.truncated
        work += res.work
        if work > PROBLEM_BUDGET or res.work >= CONFIG_BUDGET:
            gave_up = True
            break
        if res.accept != prob["pred"](s):
            first_bad = (s, prob["pred"](s))
            break
    if gave_up or exhausted:
        fails.append("the language check could not finish: your PDA's lambda transitions keep pushing "
                     "symbols, which creates too many configurations to explore (JFLAP's own Multiple Run "
                     "would stall on it too). Remove the lambda loop(s) that push without reading input")
    elif first_bad is None:
        print("  Language check: correct on all %d strings of length 0-%d over {%s}, and on longer "
              "strings." % (checked - len(long_strings(prob["num"])), max_len, ", ".join(prob["alphabet"])))
    else:
        s, want = first_bad
        msg = "your PDA does not recognize exactly the described language"
        if SHOW_COUNTEREXAMPLE:
            msg += "; a shortest string it gets wrong: %s (should be %s)" % (
                show(s), "ACCEPTED" if want else "REJECTED")
        fails.append(msg)
    if truncated_any:
        print("  Note: on some inputs your PDA kept pushing on lambda moves without reading input; the")
        print("        simulation cut those branches off. JFLAP's own Multiple Run may stall or ask about")
        print("        10000 configurations on such a PDA. A correct PDA for this problem never needs it.")

    if fails:
        for f in fails:
            print("  " + f if f.startswith("    ") else "  [FAIL] " + f)
        print("  Score: 0 / %s" % fmt(pts))
        return 0
    print("  [PASS] Score: %s / %s" % (fmt(pts), fmt(pts)))
    return pts


def read_username():
    try:
        with open("YOURUSERNAME.txt", encoding="utf-8", errors="replace") as f:
            first = f.readline().strip()
    except IOError:
        return "UNKNOWN (YOURUSERNAME.txt missing)"
    if not first:
        return "UNKNOWN (YOURUSERNAME.txt is empty)"
    return first


def selfcheck():
    """Check each test file against the target language (and the long strings' intent)."""
    ok = True
    for p in PROBLEMS:
        line = "Problem %d (%s):" % (p["num"], p["title"])
        if os.path.exists(p["tests"]):
            lines = load_tests(p["tests"])
            try:
                labels = expected_labels(len(lines))
                off = [i + 1 for i, (s, w) in enumerate(zip(lines, labels))
                       if ("accept" if p["pred"](s) else "reject") != w]
            except JFFError as e:
                off = [str(e)]
            bad_alpha = [s for s in lines if set(s) - set(p["alphabet"])]
            line += " test file %d lines, %s%s" % (
                len(lines), "consistent" if not off else "INCONSISTENT at %s" % off,
                "" if not bad_alpha else "; symbols outside the alphabet in %s" % bad_alpha)
            ok = ok and not off and not bad_alpha
        else:
            line += " test file missing"
            ok = False
        longs = long_strings(p["num"])
        n_in = sum(1 for s in longs if p["pred"](s))
        line += "; long strings: %d members, %d non-members" % (n_in, len(longs) - n_in)
        print(line)
    print("SELFCHECK " + ("OK" if ok else "FAILED"))
    return 0 if ok else 1


def main(argv):
    if "--selfcheck" in argv:
        sys.exit(selfcheck())
    wanted = sorted(set(int(a) for a in argv if a.isdigit()))
    chosen = [p for p in PROBLEMS if not wanted or p["num"] in wanted]
    username = read_username()
    print("=" * 60)
    print("CSCE 355 JFLAP5 (Pushdown Automata) - Grading Report")
    print("Username: %s" % username)
    if username.startswith("REPLACE_THIS"):
        print("WARNING: put your username on the first line of YOURUSERNAME.txt")
    print("=" * 60)
    scores = {}
    for p in chosen:
        scores[p["num"]] = grade_problem(p)
    total = sum(scores.values())
    out_of = sum(p["points"] for p in chosen)
    print("\n" + "=" * 60)
    print("USERNAME: %s" % username)
    print("TOTAL SCORE: %s / %s" % (fmt(total), fmt(out_of)))
    print("=" * 60)
    print("SCORE_LINE,%s,%s,%s,%s" % (username.replace(",", "_"), fmt(total), fmt(out_of),
                                      ",".join(fmt(scores.get(p["num"], 0)) for p in PROBLEMS)))


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(errors="replace")
    except Exception:
        pass
    main(sys.argv[1:])
