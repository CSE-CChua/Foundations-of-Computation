#!/usr/bin/env python3
"""
CSCE 355 - Turing Machine Assignment Grader
=============================================

This script grades the five .jff Turing machines in this directory against
the accompanying *_tests.txt files. It is meant to be run with no arguments
from inside a student's assignment directory:

    python3 test_tm.py

For each problem it:
  1. Parses the .jff (JFLAP save file) XML.
  2. Checks the machine for determinism. A machine that is NOT deterministic
     receives 0 points for that problem, no matter what the test strings
     say, per the assignment instructions.
  3. If deterministic, simulates the machine on each of the 20 test strings
     in the matching *_tests.txt file (first 10 should be ACCEPTED, last 10
     should be REJECTED) and awards 5 points only if all 20 match.

Total score is out of 25 (5 problems x 5 points).

Do not edit this file or the *_tests.txt files. When your assignment is
graded, they will be replaced with the master copies before this script
is run (see gradeall.py), so any local edits will not affect your grade
and may cause confusing mismatches if you are trying to debug locally.
"""

import os
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict

MAX_STEPS = 20000  # safety cap to catch infinite loops

PROBLEMS = [
    ("Problem 1: Palindrome",           "problem1_palindrome.jff",  "problem1_palindrome_tests.txt"),
    ("Problem 2: Unary Addition Check", "problem2_addition.jff",    "problem2_addition_tests.txt"),
    ("Problem 3: Binary Increment Check","problem3_increment.jff",  "problem3_increment_tests.txt"),
    ("Problem 4: Copy Check (w#w)",     "problem4_copy.jff",        "problem4_copy_tests.txt"),
    ("Problem 5: 0^n 1^n 2^n",          "problem5_anbncn.jff",      "problem5_anbncn_tests.txt"),
]

POINTS_PER_PROBLEM = 5


class TMParseError(Exception):
    pass


def parse_tm(path):
    """Parse a JFLAP .jff single-tape Turing machine file."""
    if not os.path.exists(path):
        raise TMParseError(f"file not found: {path}")

    try:
        tree = ET.parse(path)
    except ET.ParseError as e:
        raise TMParseError(f"malformed XML: {e}")

    root = tree.getroot()
    automaton = root.find("automaton")
    if automaton is None:
        raise TMParseError("no <automaton> element found")

    states = {}
    initial = None
    finals = set()
    # JFLAP's plain "Turing Machine" editor uses <state> elements; its
    # "Turing Machine (Building Blocks)" editor (type "turingbb") uses
    # <block> elements instead. For a flat machine (no block actually
    # encapsulates its own internal sub-machine) the two are otherwise
    # identical, so accept both -- this is an easy, often accidental
    # choice to make from JFLAP's New menu.
    state_like_elements = automaton.findall("state") + automaton.findall("block")
    for s in state_like_elements:
        if s.find("automaton") is not None:
            raise TMParseError(
                f"block '{s.get('name')}' contains its own nested sub-machine "
                f"(a genuine JFLAP 'building block'). This grader only supports "
                f"flat, single-level Turing machines -- please rebuild this "
                f"machine using JFLAP's plain 'Turing Machine' editor (not "
                f"'Turing Machine (Building Blocks)') without nested blocks."
            )
        sid = s.get("id")
        states[sid] = s.get("name")
        if s.find("initial") is not None:
            initial = sid
        if s.find("final") is not None:
            finals.add(sid)

    if initial is None:
        raise TMParseError("no initial state defined")

    blank_el = root.find(".//structure[@type='blank_symbol']/value")
    blank = blank_el.text if (blank_el is not None and blank_el.text is not None) else "\u25a1"

    # JFLAP nests either a bare id, or <from><id>..</id></from>-style;
    # handle both defensively.
    def extract_id(el):
        id_child = el.find("id")
        if id_child is not None and id_child.text is not None:
            return id_child.text.strip()
        return (el.text or "").strip()

    def extract_symbol(parent, *tag_names):
        """Look for the first present tag among tag_names (different JFLAP
        versions/exports use 'read0'/'write0'/'move0' or plain
        'read'/'write'/'move'). A present-but-empty tag (e.g. <read/>)
        means the blank symbol, not an unmatched/missing field."""
        for name in tag_names:
            el = parent.find(name)
            if el is not None:
                text = el.text
                if text is None or text == "":
                    return blank
                return text
        return None  # tag not present at all under any known name

    transitions = []
    for t in automaton.findall("transition"):
        frm_el = t.find("from")
        to_el = t.find("to")
        if frm_el is None or to_el is None:
            raise TMParseError("transition missing <from> or <to>")

        frm = extract_id(frm_el)
        to = extract_id(to_el)

        read = extract_symbol(t, "read0", "read")
        write = extract_symbol(t, "write0", "write")

        if read is None:
            raise TMParseError(f"transition from state {frm} has no read symbol tag")
        if write is None:
            write = read

        # Move is text-valued (R/L/S), not a tape symbol, so it should never
        # legitimately be "empty means blank" -- look it up directly.
        move_el = t.find("move0")
        if move_el is None:
            move_el = t.find("move")
        move = move_el.text.strip() if (move_el is not None and move_el.text) else "S"
        if move not in ("R", "L", "S"):
            move = "S"

        transitions.append({"from": frm, "to": to, "read": read, "write": write, "move": move})

    return {
        "initial": initial,
        "finals": finals,
        "transitions": transitions,
        "blank": blank,
    }


def check_determinism(tm):
    """Return a list of human-readable violation strings; empty list = deterministic."""
    groups = defaultdict(list)
    for t in tm["transitions"]:
        groups[(t["from"], t["read"])].append(t)

    violations = []
    for (state, symbol), group in groups.items():
        if len(group) > 1:
            dests = ", ".join(f"-> state {g['to']} (write '{g['write']}', move {g['move']})" for g in group)
            violations.append(
                f"state {state} has {len(group)} transitions reading '{symbol}': {dests}"
            )
    return violations


def simulate(tm, input_string):
    """
    Simulate a deterministic single-tape TM on input_string.
    Returns "accept", "reject", or "timeout".
    """
    blank = tm["blank"]
    tape = defaultdict(lambda: blank)
    for i, ch in enumerate(input_string):
        tape[i] = ch

    # index transitions for O(1) lookup since machine is deterministic
    delta = {}
    for t in tm["transitions"]:
        delta[(t["from"], t["read"])] = t

    state = tm["initial"]
    head = 0
    steps = 0

    if state in tm["finals"]:
        return "accept"

    while steps < MAX_STEPS:
        symbol = tape[head]
        key = (state, symbol)
        if key not in delta:
            return "reject"  # no applicable transition -> halt, not accepting

        t = delta[key]
        tape[head] = t["write"]
        if t["move"] == "R":
            head += 1
        elif t["move"] == "L":
            head -= 1
        # 'S' (stay) -> no head movement

        state = t["to"]
        steps += 1

        if state in tm["finals"]:
            return "accept"

    return "timeout"


def load_test_strings(path):
    if not os.path.exists(path):
        raise TMParseError(f"test file not found: {path}")
    with open(path, "r") as f:
        lines = f.read().split("\n")
    # drop a single trailing empty element caused by final newline
    if lines and lines[-1] == "":
        lines = lines[:-1]
    return lines


def grade_problem(label, jff_path, tests_path):
    print(f"\n{'-'*60}")
    print(label)
    print(f"{'-'*60}")

    try:
        tm = parse_tm(jff_path)
    except TMParseError as e:
        print(f"  [FAIL] Could not parse {jff_path}: {e}")
        print(f"  Score: 0 / {POINTS_PER_PROBLEM}")
        return 0

    violations = check_determinism(tm)
    if violations:
        print(f"  [FAIL] Machine is NOT deterministic. No credit per assignment rules.")
        print(f"  Conflicting transitions found:")
        for v in violations:
            print(f"    - {v}")
        print(f"  Score: 0 / {POINTS_PER_PROBLEM}")
        return 0

    try:
        test_lines = load_test_strings(tests_path)
    except TMParseError as e:
        print(f"  [FAIL] {e}")
        print(f"  Score: 0 / {POINTS_PER_PROBLEM}")
        return 0

    if len(test_lines) != 20:
        print(f"  [WARN] Expected 20 test lines in {tests_path}, found {len(test_lines)}.")

    expected = ["accept"] * 10 + ["reject"] * 10
    mismatches = []

    for i, s in enumerate(test_lines):
        want = expected[i] if i < len(expected) else None
        got = simulate(tm, s)
        got_bucket = "accept" if got == "accept" else "reject"  # timeout counts as not-accept
        display_s = s if s != "" else "(empty string)"
        if want is not None and got_bucket != want:
            mismatches.append(
                f"line {i+1}: input {display_s!r} expected {want.upper()}, "
                f"machine result: {got.upper()}"
            )

    if mismatches:
        print(f"  [FAIL] {len(mismatches)} of {len(test_lines)} test string(s) did not match:")
        for m in mismatches:
            print(f"    - {m}")
        print(f"  Score: 0 / {POINTS_PER_PROBLEM}")
        return 0

    print(f"  [PASS] Deterministic and all {len(test_lines)} test strings correct.")
    print(f"  Score: {POINTS_PER_PROBLEM} / {POINTS_PER_PROBLEM}")
    return POINTS_PER_PROBLEM


def read_username():
    path = "YOURUSERNAME.txt"
    if not os.path.exists(path):
        return "UNKNOWN (YOURUSERNAME.txt missing)"
    with open(path, "r") as f:
        first_line = f.readline().strip()
    if not first_line:
        return "UNKNOWN (YOURUSERNAME.txt is empty)"
    return first_line


def main():
    username = read_username()
    print("=" * 60)
    print("CSCE 355 Turing Machine Assignment - Grading Report")
    print(f"Username: {username}")
    print("=" * 60)

    total = 0
    for label, jff_name, tests_name in PROBLEMS:
        total += grade_problem(label, jff_name, tests_name)

    print(f"\n{'='*60}")
    print(f"USERNAME: {username}")
    print(f"TOTAL SCORE: {total} / 25")
    print(f"{'='*60}")

    # Machine-readable summary line for gradeall.py to parse.
    print(f"SCORE_LINE,{username},{total},25")


if __name__ == "__main__":
    main()
