class RefNFA(object):
    """Reference machine; used deterministically through on-the-fly subset construction."""
    def __init__(self, start, finals, edges):
        self.finals = set(finals)
        self.delta = {}
        for frm, sym, to in edges:
            self.delta.setdefault((frm, sym), set()).add(to)
        self.start = self.closure({start})

    def closure(self, S):
        out, todo = set(S), list(S)
        while todo:
            q = todo.pop()
            for r in self.delta.get((q, ""), ()):
                if r not in out:
                    out.add(r)
                    todo.append(r)
        return frozenset(out)

    def step(self, S, ch):
        nxt = set()
        for q in S:
            nxt |= self.delta.get((q, ch), set())
        return self.closure(nxt)

    def accept(self, S):
        return bool(S & self.finals)


def loops(state, symbols):
    return [(state, a, state) for a in symbols]


def word_star_nfa(words):
    """(w1 + w2 + ...)* as an NFA: a hub state B, one path of fresh states per word."""
    edges = []
    for k, w in enumerate(words):
        prev = "B"
        for i, ch in enumerate(w):
            nxt = "B" if i == len(w) - 1 else (k, i)
            edges.append((prev, ch, nxt))
            prev = nxt
    return RefNFA("B", ["B"], edges)


