def grade_problem(prob):
    pts = prob["points"]
    print("\n" + "-" * 60)
    print("Problem %d: %s  (%s points)" % (prob["num"], prob["title"], fmt(pts)))
    print("-" * 60)
    print("  File: %s" % prob["jff"])
    fails = []

    try:
        fa = parse_jff(prob["jff"])
        nfa, problems = check_nfa(fa, prob)
    except JFFError as e:
        print("  [FAIL] %s" % e)
        print("  Score: 0 / %s" % fmt(pts))
        return 0
    if problems:
        print("  [FAIL] The machine does not have the required form, so it earns no credit:")
        for p in problems:
            print("    - %s" % p)
        print("  Score: 0 / %s" % fmt(pts))
        return 0
    print("  Form check passed (%s): %d states (%d reachable), %d transitions (%d lambda)."
          % ("lambda-NFA" if prob["lambda_ok"] else "NFA, no lambda transitions",
             nfa["n_states"], nfa["n_reachable"], nfa["n_edges"], nfa["n_lambda"]))
    if nfa["comma_labels"]:
        print("  Note: comma-separated labels are graded as one transition per symbol, and each one counts")
        print("        toward the size limit. JFLAP's own Input -> Multiple Run does NOT split them (it reads")
        print("        '0,1' as a 3-character string), so JFLAP will disagree with this report. Draw a")
        print("        separate transition for each symbol instead. Labels found:")
        for c in nfa["comma_labels"][:MAX_LISTED]:
            print("          %s" % c)
    m = student_machine(nfa)

    # provided test file
    try:
        lines = load_tests(prob["tests"])
        labels = expected_labels(prob["split"], len(lines))
    except JFFError as e:
        print("  [FAIL] %s" % e)
        print("  Score: 0 / %s" % fmt(pts))
        return 0
    wrong = []
    for i, (s, want) in enumerate(zip(lines, labels), 1):
        got = "accept" if run_machine(m, s) else "reject"
        if got != want:
            wrong.append("line %d: %s -> expected %s, your machine %ss" % (i, show(s), want.upper(), got))
    if wrong:
        fails.append("%d of %d provided test strings are wrong:" % (len(wrong), len(lines)))
        fails += ["    " + w for w in wrong[:MAX_LISTED]]
        if len(wrong) > MAX_LISTED:
            fails.append("    ... and %d more" % (len(wrong) - MAX_LISTED))
    else:
        print("  Provided tests: all %d strings correct." % len(lines))

    # empty string (not covered by the test files)
    if not prob["dont_care_empty"]:
        want_empty = prob["ref"].accept(prob["ref"].start)
        got_empty = run_machine(m, "")
        if want_empty == got_empty:
            print("  Empty string: %s, as required." % ("accepted" if got_empty else "rejected"))
        else:
            fails.append("the empty string must be %s, but your machine %s it"
                         % ("accepted" if want_empty else "rejected", "accepts" if got_empty else "rejects"))

    # exact language
    if EXACT_CHECK:
        ce = find_counterexample(m, prob)
        if ce is None:
            print("  Language check: your machine matches the target language exactly.")
        else:
            s, want = ce
            msg = "your machine does not recognize exactly the described language"
            if SHOW_COUNTEREXAMPLE:
                msg += "; a shortest string it gets wrong: %s (should be %s)" % (
                    show(s), "ACCEPTED" if want else "REJECTED")
            fails.append(msg)

    # lambda transitions used productively
    if prob["lambda_productive"]:
        if nfa["n_lambda"] == 0:
            fails.append("this problem asks for a lambda-NFA, and your machine has no lambda transitions "
                         "(an NFA without them, even a correct one, does not count here)")
        elif find_counterexample(student_machine(nfa, use_lambda=False), prob) is None:
            fails.append("your lambda transitions are not used productively: deleting all of them leaves "
                         "the language unchanged")
        else:
            print("  Lambda transitions: %d, used productively (deleting them changes the language)."
                  % nfa["n_lambda"])

    if fails:
        for f in fails:
            print("  " + f if f.startswith("    ") else "  [FAIL] " + f)
        print("  Score: 0 / %s" % fmt(pts))
        return 0

    # size limit: -50% per extra state / edge
    extra, what = 0, None
    if prob["max_states"] is not None:
        extra, what = nfa["n_states"] - prob["max_states"], ("states", nfa["n_states"], prob["max_states"])
    if prob["max_edges"] is not None:
        extra, what = nfa["n_edges"] - prob["max_edges"], ("edges", nfa["n_edges"], prob["max_edges"])
    score = pts
    if what is not None:
        if extra > 0:
            score = pts * max(0.0, 1 - PENALTY_PER_EXTRA * extra)
            print("  [PENALTY] %d %s; the limit is %d. %d over the limit: -%d%%.%s"
                  % (what[1], what[0], what[2], extra, min(100, round(100 * PENALTY_PER_EXTRA * extra)),
                     "" if nfa["n_reachable"] == nfa["n_states"] else
                     " (The file has %d unreachable state(s): delete anything you are not using.)"
                     % (nfa["n_states"] - nfa["n_reachable"])))
        else:
            print("  Size: %d %s, within the limit of %d." % (what[1], what[0], what[2]))
    print("  [%s] Score: %s / %s" % ("PASS" if score == pts else "PARTIAL" if score > 0 else "OVER LIMIT",
                                      fmt(score), fmt(pts)))
    return score


def read_username():
    try:
        with open("YOURUSERNAME.txt", encoding="utf-8", errors="replace") as f:
            first = f.readline().strip()
    except IOError:
        return "UNKNOWN (YOURUSERNAME.txt missing)"
    if not first:
        return "UNKNOWN (YOURUSERNAME.txt is empty)"
    return first


def selfcheck():
    """Verify the reference machines and the published regexes against independent membership tests."""
    ok = True
    for p in PROBLEMS:
        rx = re.compile(course_regex_to_python(REGEX[p["num"]]))
        n, bad = 0, None
        for length in range(SELFCHECK_LEN + 1):
            for tup in itertools.product(sorted(p["alphabet"]), repeat=length):
                s = "".join(tup)
                if s == "" and p["dont_care_empty"]:
                    continue
                n += 1
                want = PRED[p["num"]](s)
                if run_machine(p["ref"], s) != want or (rx.fullmatch(s) is not None) != want:
                    bad = s
                    break
            if bad is not None:
                break
        line = ("Problem %d: reference machine and regex %s agree with the independent check on %d strings"
                % (p["num"], REGEX[p["num"]], n))
        if bad is not None:
            ok = False
            line = "Problem %d: MISMATCH on %r" % (p["num"], bad)
        if os.path.exists(p["tests"]):
            lines = load_tests(p["tests"])
            labels = expected_labels(p["split"], len(lines))
            off = [i + 1 for i, (s, w) in enumerate(zip(lines, labels))
                   if ("accept" if PRED[p["num"]](s) else "reject") != w
                   or ("accept" if run_machine(p["ref"], s) else "reject") != w]
            line += "; test file: %d lines, %s" % (len(lines),
                                                  "consistent" if not off else "INCONSISTENT at lines %s" % off)
            ok = ok and not off
        print(line)
    print("SELFCHECK " + ("OK" if ok else "FAILED"))
    return 0 if ok else 1


