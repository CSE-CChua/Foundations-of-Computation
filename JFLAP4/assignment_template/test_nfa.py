# Reading the .jff file
# ---------------------------------------------------------------------------
class JFFError(Exception):
    pass


LAMBDA_TEXT = ("", "λ", "ε")     # lambda / epsilon spellings of the empty string


def parse_jff(path):
    if not os.path.exists(path):
        raise JFFError("file not found: %s" % path)
    try:
        root = ET.parse(path).getroot()
    except ET.ParseError as e:
        raise JFFError("the file is not valid JFLAP XML (%s)" % e)
    kind = (root.findtext("type") or "").strip()
    if kind != "fa":
        raise JFFError("this file holds a '%s' machine, but this assignment needs a Finite Automaton "
                       "(in JFLAP choose 'Finite Automaton', not a Turing machine, pushdown "
                       "automaton, etc.)" % (kind or "unknown"))
    aut = root.find("automaton")
    if aut is None:
        raise JFFError("no <automaton> element found")
    states, initial, finals = {}, [], set()
    for s in aut.findall("state"):
        sid = s.get("id")
        states[sid] = s.get("name") or ("q" + str(sid))
        if s.find("initial") is not None:
            initial.append(sid)
        if s.find("final") is not None:
            finals.add(sid)
    edges = []
    for t in aut.findall("transition"):
        frm = (t.findtext("from") or "").strip()
        to = (t.findtext("to") or "").strip()
        read = t.find("read")
        text = "" if (read is None or read.text is None) else read.text
        edges.append((frm, text, to))
    return dict(states=states, initial=initial, finals=finals, edges=edges)


def check_nfa(fa, prob):
    """Return (nfa, problems). 'problems' lists reasons the machine has the wrong form."""
    alphabet = prob["alphabet"]
    states = fa["states"]
    name = lambda sid: states.get(sid, "?")
    if not states:
        raise JFFError("the file contains no states: it is still the empty template")
    if not fa["initial"]:
        raise JFFError("no initial state is set (right-click a state and choose 'Initial')")
    problems = []
    if len(fa["initial"]) > 1:
        problems.append("more than one initial state (%s)" % ", ".join(name(i) for i in fa["initial"]))

    edges, comma_labels = [], []
    for frm, text, to in fa["edges"]:
        if frm not in states or to not in states:
            problems.append("a transition refers to a state that does not exist")
            continue
        t = text.strip()
        where = "transition %s -> %s" % (name(frm), name(to))
        if "," in t:
            # A comma-separated label such as "0,1" is graded as one transition per symbol,
            # and each one counts separately toward a size limit.
            parts = [x.strip() for x in t.split(",") if x.strip() != ""] or [""]
            comma_labels.append("%s labeled '%s' (counted as %d transitions)" % (where, t, len(parts)))
        else:
            parts = [t]
        for sym in parts:
            if sym in LAMBDA_TEXT:
                if not prob["lambda_ok"]:
                    problems.append("%s is a lambda (empty-string) transition; this problem asks for an NFA "
                                    "without lambda transitions" % where)
                edges.append((frm, "", to))
            elif len(sym) != 1:
                problems.append("%s reads '%s', which is more than one symbol; each transition must read "
                                "exactly one symbol (or be a lambda transition where allowed)" % (where, sym))
            elif sym not in alphabet:
                problems.append("%s reads '%s', which is not in the alphabet {%s}"
                                % (where, sym, ", ".join(alphabet)))
            else:
                edges.append((frm, sym, to))

    init = fa["initial"][0]
    seen, queue = {init}, deque([init])
    while queue:
        q = queue.popleft()
        for frm, sym, to in edges:
            if frm == q and to not in seen:
                seen.add(to)
                queue.append(to)
    nfa = dict(edges=edges, initial=init, finals=fa["finals"], n_states=len(states),
               n_reachable=len(seen), n_edges=len(edges), n_lambda=sum(1 for e in edges if e[1] == ""),
               comma_labels=comma_labels, name=name)
    return nfa, problems


def student_machine(nfa, use_lambda=True):
    edges = [e for e in nfa["edges"] if use_lambda or e[1] != ""]
    return RefNFA(nfa["initial"], nfa["finals"], edges)


def run_machine(m, s):
    S = m.start
    for ch in s:
        S = m.step(S, ch)
        if not S:
            return False
    return m.accept(S)


# ---------------------------------------------------------------------------
# Test files and the exact-language check
# ---------------------------------------------------------------------------
def show(s):
    if s == "":
        return "(empty string)"
    return s if len(s) <= MAX_DISPLAY else "%s... (length %d)" % (s[:MAX_DISPLAY], len(s))


def load_tests(path):
    if not os.path.exists(path):
        raise JFFError("test file not found: %s" % path)
    with open(path, encoding="utf-8", errors="replace", newline=None) as f:
        lines = f.read().split("\n")
    while lines and lines[-1] == "":        # ignore stray blank lines at the end
        lines.pop()
    return lines


def expected_labels(split, n):
    fixed = sum(c for _, c in split if c is not None)
    labels = []
    for lab, c in split:
        labels += [lab] * (c if c is not None else n - fixed)
    if len(labels) != n:
        raise JFFError("test data error: expected %d test lines but found %d" % (len(labels), n))
    return labels


def find_counterexample(m, prob):
    """Shortest string on which machine m and the target language disagree, or None.
    Breadth-first search over pairs (reference subset, student subset)."""
    ref, alphabet = prob["ref"], sorted(prob["alphabet"])
    seen = {(ref.start, m.start)}
    queue = deque([(ref.start, m.start, "")])
    while queue:
        r, q, path = queue.popleft()
        if not (path == "" and prob["dont_care_empty"]):
            want, got = ref.accept(r), m.accept(q)
            if want != got:
                return path, want
        for ch in alphabet:
            r2, q2 = ref.step(r, ch), m.step(q, ch)
            if (r2, q2) not in seen:
                seen.add((r2, q2))
                queue.append((r2, q2, path + ch))
    return None


