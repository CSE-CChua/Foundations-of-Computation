# Independent, obviously-correct membership tests (used only by --selfcheck)
def _in_word_star(s, words):
    ok = [True] + [False] * len(s)
    for i in range(1, len(s) + 1):
        ok[i] = any(i >= len(w) and ok[i - len(w)] and s[i - len(w):i] == w for w in words)
    return ok[-1]


def _has_10i1(s):
    for i in range(len(s)):
        if s[i] == "1":
            j = i + 1
            while j < len(s) and s[j] == "0":
                j += 1
            z = j - i - 1
            if j < len(s) and s[j] == "1" and z > 0 and (z % 2 == 0 or z % 3 == 0):
                return True
    return False


