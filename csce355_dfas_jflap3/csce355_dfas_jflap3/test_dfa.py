# ---------------------------------------------------------------------------
# Reading the .jff file
# ---------------------------------------------------------------------------
class JFFError(Exception):
    pass


LAMBDA_TEXT = ("", "\u03bb", "\u03b5")     # lambda / epsilon spellings of the empty string


def parse_jff(path):
    if not os.path.exists(path):
        raise JFFError("file not found: %s" % path)
    try:
        root = ET.parse(path).getroot()
    except ET.ParseError as e:
        raise JFFError("the file is not valid JFLAP XML (%s)" % e)
    kind = (root.findtext("type") or "").strip()
    if kind != "fa":
        raise JFFError("this file holds a '%s' machine, but this assignment needs a Finite Automaton "
                       "(in JFLAP choose 'Finite Automaton', not a Turing machine, pushdown "
                       "automaton, etc.)" % (kind or "unknown"))
    aut = root.find("automaton")
    if aut is None:
        raise JFFError("no <automaton> element found")
    states, initial, finals = {}, [], set()
    for s in aut.findall("state"):
        sid = s.get("id")
        states[sid] = s.get("name") or ("q" + str(sid))
        if s.find("initial") is not None:
            initial.append(sid)
        if s.find("final") is not None:
            finals.add(sid)
    edges = []
    for t in aut.findall("transition"):
        frm = (t.findtext("from") or "").strip()
        to = (t.findtext("to") or "").strip()
        read = t.find("read")
        text = "" if (read is None or read.text is None) else read.text.strip()
        edges.append((frm, text, to))
    return dict(states=states, initial=initial, finals=finals, edges=edges)


def split_label(text):
    """A JFLAP label may list several symbols separated by commas (e.g. '0,1')."""
    if text.strip() in LAMBDA_TEXT:
        return [""]
    parts = [p.strip() for p in text.split(",")]
    parts = [p for p in parts if p != ""]
    if not parts:
        return [""]
    return ["" if p in LAMBDA_TEXT else p for p in parts]


def check_dfa(fa, alphabet):
    """Return (dfa, problems, notes). 'problems' lists reasons the machine is not a DFA."""
    states = fa["states"]
    name = lambda sid: states.get(sid, "?")
    if not states:
        raise JFFError("the file contains no states: it is still the empty template")
    if not fa["initial"]:
        raise JFFError("no initial state is set (right-click a state and choose 'Initial')")
    problems, notes = [], []
    if len(fa["initial"]) > 1:
        problems.append("more than one initial state (%s)" % ", ".join(name(i) for i in fa["initial"]))

    targets, lam = {}, []
    for frm, text, to in fa["edges"]:
        if frm not in states or to not in states:
            problems.append("a transition refers to a state that does not exist")
            continue
        for sym in split_label(text):
            if sym == "":
                lam.append((frm, to))
            elif len(sym) != 1:
                problems.append("transition %s -> %s reads '%s', which is more than one symbol; "
                                "a DFA transition reads exactly one symbol" % (name(frm), name(to), sym))
            elif sym not in alphabet:
                problems.append("transition %s -> %s reads '%s', which is not in the alphabet {%s}"
                                % (name(frm), name(to), sym, ", ".join(alphabet)))
            else:
                targets.setdefault((frm, sym), set()).add(to)

    for (st, sym), tg in sorted(targets.items(), key=lambda kv: (name(kv[0][0]), kv[0][1])):
        if len(tg) > 1:
            problems.append("state %s has %d different transitions on '%s' (to %s)"
                            % (name(st), len(tg), sym, ", ".join(sorted(name(t) for t in tg))))
    for frm, to in sorted(set(lam), key=lambda e: (name(e[0]), name(e[1]))):
        problems.append("state %s has a lambda (empty-string) transition to %s; a DFA may not have "
                        "lambda transitions" % (name(frm), name(to)))

    missing = [(s, a) for s in states for a in alphabet if (s, a) not in targets]
    if missing:
        if REQUIRE_COMPLETE:
            by_state = {}
            for s, a in missing:
                by_state.setdefault(s, []).append(a)
            ordered = sorted(by_state.items(), key=lambda kv: name(kv[0]))
            for s, syms in ordered[:8]:
                problems.append("not a complete DFA: state %s has no transition on %s"
                                % (name(s), " or ".join("'%s'" % a for a in syms)))
            if len(ordered) > 8:
                problems.append("... and %d more states with missing transitions" % (len(ordered) - 8))
            problems.append("a DFA needs exactly one transition per state and symbol: add a trap (dead) "
                            "state that loops to itself on every symbol, and send every missing "
                            "transition to it")
        else:
            notes.append("%d missing transition(s) are treated as 'reject' (JFLAP does the same)"
                         % len(missing))

    delta = {k: next(iter(v)) for k, v in targets.items() if len(v) == 1}
    init = fa["initial"][0]
    seen, queue = {init}, deque([init])
    while queue:
        q = queue.popleft()
        for a in alphabet:
            q2 = delta.get((q, a))
            if q2 is not None and q2 not in seen:
                seen.add(q2)
                queue.append(q2)
    dfa = dict(delta=delta, initial=init, finals=fa["finals"], n_states=len(states),
               n_reachable=len(seen), n_edges=len(targets), name=name)
    return dfa, problems, notes


def accepts(dfa, s):
    q = dfa["initial"]
    for ch in s:
        q = dfa["delta"].get((q, ch))
        if q is None:
            return False
    return q in dfa["finals"]


# ---------------------------------------------------------------------------
# Test files and the exact-language check
# ---------------------------------------------------------------------------
def show(s):
    if s == "":
        return "(empty string)"
    return s if len(s) <= MAX_DISPLAY else "%s... (length %d)" % (s[:MAX_DISPLAY], len(s))


def load_tests(path):
    if not os.path.exists(path):
        raise JFFError("test file not found: %s" % path)
    with open(path, encoding="utf-8", errors="replace", newline=None) as f:
        lines = f.read().split("\n")
    while lines and lines[-1] == "":        # ignore stray blank lines at the end
        lines.pop()
    return lines


def expected_labels(split, n):
    fixed = sum(c for _, c in split if c is not None)
    labels = []
    for lab, c in split:
        labels += [lab] * (c if c is not None else n - fixed)
    if len(labels) != n:
        raise JFFError("test data error: expected %d test lines but found %d" % (len(labels), n))
    return labels


def find_counterexample(dfa, prob):
    """Shortest string on which the DFA and the target language disagree, or None.
    Breadth-first search over pairs (reference state, student state)."""
    ref, alphabet = prob["ref"], sorted(prob["alphabet"])
    seen = {(ref.start, dfa["initial"])}
    queue = deque([(ref.start, dfa["initial"], "")])
    while queue:
        r, q, path = queue.popleft()
        if not (path == "" and prob["dont_care_empty"]):
            want = ref.accept(r)
            got = q is not None and q in dfa["finals"]
            if want != got:
                return path, want
        for ch in alphabet:
            r2 = ref.step(r, ch)
            q2 = None if q is None else dfa["delta"].get((q, ch))
            if (r2, q2) not in seen:
                seen.add((r2, q2))
                queue.append((r2, q2, path + ch))
    return None


