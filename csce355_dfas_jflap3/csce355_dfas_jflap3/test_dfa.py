#!/usr/bin/env python3
"""
CSCE 355 - JFLAP3 (DFA assignment) grader
==========================================

Run from inside your assignment folder:

    python3 test_dfa.py              # grade all seven problems
    python3 test_dfa.py 3            # grade only Problem 3
    python3 test_dfa.py --selfcheck  # (instructors) verify the built-in target languages

For every problem the script:

  1. Parses the .jff file. It must be a JFLAP *Finite Automaton*.
  2. Checks that it really is a DFA, BEFORE running any test string:
       - exactly one transition per (state, symbol): none missing, none
         repeated. Unlike JFLAP, you must draw an explicit trap (dead) state
         instead of leaving transitions out;
       - no lambda (empty-string) transitions;
       - every transition reads exactly one symbol, and that symbol is in
         the problem's alphabet;
       - exactly one initial state.
     A machine that is not a DFA earns 0 points for that problem.
  3. Runs the strings in the provided *_tests.txt file and compares each
     against the expected accept/reject result.
  4. Compares your DFA with the exact target language (product-automaton
     search). If they differ it prints a shortest string on which your DFA is wrong,
     so passing the sample strings alone is not enough.
  5. Awards the problem's points only if every check passes
     (no partial credit within a problem).

Do not edit this file or the *_tests.txt files: the graders replace them with
the master copies before grading (see gradeall.py).
"""

