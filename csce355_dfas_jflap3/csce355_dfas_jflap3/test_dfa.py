def grade_problem(prob):
    pts = prob["points"]
    print("\n" + "-" * 60)
    print("Problem %d: %s  (%d points)" % (prob["num"], prob["title"], pts))
    print("-" * 60)
    print("  File: %s" % prob["jff"])
    fails = []

    try:
        fa = parse_jff(prob["jff"])
        dfa, problems, notes = check_dfa(fa, prob["alphabet"])
    except JFFError as e:
        print("  [FAIL] %s" % e)
        print("  Score: 0 / %d" % pts)
        return 0

    if problems:
        print("  [FAIL] This is NOT a DFA, so it earns no credit. Problems found:")
        for p in problems:
            print("    - %s" % p)
        print("  Score: 0 / %d" % pts)
        return 0
    print("  DFA check passed: %d states (%d reachable), %d transitions, deterministic."
          % (dfa["n_states"], dfa["n_reachable"], dfa["n_edges"]))
    for n in notes:
        print("  Note: %s" % n)

    if prob["max_states"] is not None and dfa["n_reachable"] > prob["max_states"]:
        fails.append("uses %d reachable states; the limit is %d (unreachable states may be deleted)"
                     % (dfa["n_reachable"], prob["max_states"]))

    # provided test file
    try:
        lines = load_tests(prob["tests"])
        labels = expected_labels(prob["split"], len(lines))
    except JFFError as e:
        print("  [FAIL] %s" % e)
        print("  Score: 0 / %d" % pts)
        return 0
    wrong = []
    for i, (s, want) in enumerate(zip(lines, labels), 1):
        got = "accept" if accepts(dfa, s) else "reject"
        if got != want:
            wrong.append("line %d: %s -> expected %s, your DFA %ss" % (i, show(s), want.upper(), got))
    if wrong:
        fails.append("%d of %d provided test strings are wrong:" % (len(wrong), len(lines)))
        fails += ["    " + w for w in wrong[:MAX_LISTED]]
        if len(wrong) > MAX_LISTED:
            fails.append("    ... and %d more" % (len(wrong) - MAX_LISTED))
    else:
        print("  Provided tests: all %d strings correct." % len(lines))

    # empty string (not covered by the test files)
    if not prob["dont_care_empty"]:
        want_empty = prob["ref"].accept(prob["ref"].start)
        got_empty = accepts(dfa, "")
        if want_empty == got_empty:
            print("  Empty string: %s, as required." % ("accepted" if got_empty else "rejected"))
        else:
            fails.append("the empty string must be %s, but your DFA %s it"
                         % ("accepted" if want_empty else "rejected", "accepts" if got_empty else "rejects"))

    # exact language
    if EXACT_CHECK:
        ce = find_counterexample(dfa, prob)
        if ce is None:
            print("  Language check: your DFA matches the target language exactly.")
        else:
            s, want = ce
            msg = "your DFA does not recognize exactly the described language"
            if SHOW_COUNTEREXAMPLE:
                msg += "; a shortest string it gets wrong: %s (should be %s)" % (
                    show(s), "ACCEPTED" if want else "REJECTED")
            fails.append(msg)

    if fails:
        for f in fails:
            print("  " + f if f.startswith("    ") else "  [FAIL] " + f)
        print("  Score: 0 / %d" % pts)
        return 0
    print("  [PASS] Score: %d / %d" % (pts, pts))
    return pts


def read_username():
    try:
        with open("YOURUSERNAME.txt", encoding="utf-8", errors="replace") as f:
            first = f.readline().strip()
    except IOError:
        return "UNKNOWN (YOURUSERNAME.txt missing)"
    if not first:
        return "UNKNOWN (YOURUSERNAME.txt is empty)"
    return first


def selfcheck():
    """Verify the built-in reference machines against independent membership tests."""
    ok = True
    for p in PROBLEMS:
        n, bad = 0, None
        for length in range(SELFCHECK_LEN + 1):
            for tup in itertools.product(sorted(p["alphabet"]), repeat=length):
                s = "".join(tup)
                if s == "" and p["dont_care_empty"]:
                    continue
                n += 1
                if run_machine(p["ref"], s) != PRED[p["num"]](s):
                    bad = s
                    break
            if bad is not None:
                break
        line = "Problem %d: reference machine agrees with the independent check on %d strings" % (p["num"], n)
        if bad is not None:
            ok = False
            line = "Problem %d: MISMATCH on %r" % (p["num"], bad)
        if os.path.exists(p["tests"]):
            lines = load_tests(p["tests"])
            labels = expected_labels(p["split"], len(lines))
            off = [i + 1 for i, (s, w) in enumerate(zip(lines, labels))
                   if ("accept" if run_machine(p["ref"], s) else "reject") != w]
            line += "; test file: %d lines, %s" % (len(lines),
                                                  "consistent" if not off else "INCONSISTENT at lines %s" % off)
            ok = ok and not off
        print(line)
    print("SELFCHECK " + ("OK" if ok else "FAILED"))
    return 0 if ok else 1


def main(argv):
    if "--selfcheck" in argv:
        sys.exit(selfcheck())
    wanted = sorted(set(int(a) for a in argv if a.isdigit()))
    chosen = [p for p in PROBLEMS if not wanted or p["num"] in wanted]

    username = read_username()
    print("=" * 60)
    print("CSCE 355 JFLAP3 (DFAs) - Grading Report")
    print("Username: %s" % username)
    if username.startswith("REPLACE_THIS"):
        print("WARNING: put your username on the first line of YOURUSERNAME.txt")
    print("=" * 60)

    scores = {}
    for p in chosen:
        scores[p["num"]] = grade_problem(p)
    total = sum(scores.values())
    out_of = sum(p["points"] for p in chosen)

    print("\n" + "=" * 60)
    print("USERNAME: %s" % username)
    print("TOTAL SCORE: %d / %d" % (total, out_of))
    print("=" * 60)
    safe_name = username.replace(",", "_")
    print("SCORE_LINE,%s,%d,%d,%s" % (safe_name, total, out_of,
                                      ",".join(str(scores.get(p["num"], 0)) for p in PROBLEMS)))


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(errors="replace")     # never crash on odd characters
    except Exception:
        pass
    main(sys.argv[1:])
