#!/usr/bin/env python3
"""
CSCE 355 - Turing Machine Assignment Grader
=============================================

This script grades the six .jff Turing machines in this directory against
the accompanying test files. It is meant to be run with no arguments from
inside a student's assignment directory:

    python3 test_tm.py

For each problem it:
  1. Parses the .jff (JFLAP save file) XML.
  2. Checks the machine for determinism. A machine that is NOT deterministic
     receives 0 points for that problem, no matter what the test data says,
     per the assignment instructions.
  3. If deterministic, tests the machine against its test file:
       - DECISION problems (1-4): the *_tests.txt file has 20 lines, the
         first 10 strings must be ACCEPTED and the last 10 must be
         REJECTED.
       - TRANSDUCER problems (5-6): the *_tests.txt file has one input
         string per line, and the paired *_expected_outputs.txt file has
         the required output on the corresponding line (same order, same
         line count). The machine must halt (in any state -- transducers
         need not have a final state) with the correct output starting
         at the head's position and running to the first blank symbol to
         its right. See the assignment instructions for why output is
         read this way.
  4. Awards full credit for a problem only if the machine is deterministic
     AND every test case for that problem is correct. There is no partial
     credit within a single problem.

Do not edit this file, any *_tests.txt file, or any *_expected_outputs.txt
file. When your assignment is
graded, they will be replaced with the master copies before this script
is run (see gradeall.py), so any local edits will not affect your grade
and may cause confusing mismatches if you are trying to debug locally.
"""

import os
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict

MAX_STEPS = 20000  # safety cap to catch infinite loops

# label, jff filename, tests filename, kind ("decision" or "transducer"), points
PROBLEMS = [
    ("Problem 1: Contains a 1",        "problem1_contains1.jff", "problem1_contains1_tests.txt", "decision",   4),
    ("Problem 2: Ends with 0",         "problem2_endswith0.jff", "problem2_endswith0_tests.txt", "decision",   4),
    ("Problem 3: Even Number of 1s",   "problem3_evenones.jff",  "problem3_evenones_tests.txt",  "decision",   4),
    ("Problem 4: Equal 0s and 1s",     "problem4_equalcount.jff","problem4_equalcount_tests.txt","decision",   4),
    ("Problem 5: Flip All Bits",       "problem5_flipbits.jff",
        ("problem5_flipbits_tests.txt", "problem5_flipbits_expected_outputs.txt"), "transducer", 4),
    ("Problem 6: Delete Duplicate Runs","problem6_deletedup.jff",
        ("problem6_deletedup_tests.txt", "problem6_deletedup_expected_outputs.txt"), "transducer", 5),
]

TOTAL_POSSIBLE = sum(p[4] for p in PROBLEMS)  # 25


class TMParseError(Exception):
    pass


def parse_tm(path):
    """Parse a JFLAP .jff single-tape Turing machine file."""
    if not os.path.exists(path):
        raise TMParseError(f"file not found: {path}")

    try:
        tree = ET.parse(path)
    except ET.ParseError as e:
        raise TMParseError(f"malformed XML: {e}")

    root = tree.getroot()
    automaton = root.find("automaton")
    if automaton is None:
        raise TMParseError("no <automaton> element found")

    states = {}
    initial = None
    finals = set()
    for s in automaton.findall("state"):
        sid = s.get("id")
        states[sid] = s.get("name")
        if s.find("initial") is not None:
            initial = sid
        if s.find("final") is not None:
            finals.add(sid)

    if initial is None:
        raise TMParseError("no initial state defined")

    blank_el = root.find(".//structure[@type='blank_symbol']/value")
    blank = blank_el.text if (blank_el is not None and blank_el.text is not None) else "\u25a1"

    def extract_id(el):
        # JFLAP nests either a bare id, or <from><id>..</id></from>-style.
        id_child = el.find("id")
        if id_child is not None and id_child.text is not None:
            return id_child.text.strip()
        return (el.text or "").strip()

    def extract_symbol(parent, *tag_names):
        """Look for the first present tag among tag_names (different JFLAP
        versions/exports use 'read0'/'write0' or plain 'read'/'write').
        A present-but-empty tag (e.g. <read/>) means the blank symbol,
        not an unmatched/missing field."""
        for name in tag_names:
            el = parent.find(name)
            if el is not None:
                text = el.text
                if text is None or text == "":
                    return blank
                return text
        return None  # tag not present at all under any known name

    transitions = []
    for t in automaton.findall("transition"):
        frm_el = t.find("from")
        to_el = t.find("to")
        if frm_el is None or to_el is None:
            raise TMParseError("transition missing <from> or <to>")

        frm = extract_id(frm_el)
        to = extract_id(to_el)

        read = extract_symbol(t, "read0", "read")
        write = extract_symbol(t, "write0", "write")

        if read is None:
            raise TMParseError(f"transition from state {frm} has no read symbol tag")
        if write is None:
            write = read

        move_el = t.find("move0")
        if move_el is None:
            move_el = t.find("move")
        move = move_el.text.strip() if (move_el is not None and move_el.text) else "S"
        if move not in ("R", "L", "S"):
            move = "S"

        transitions.append({"from": frm, "to": to, "read": read, "write": write, "move": move})

    return {
        "initial": initial,
        "finals": finals,
        "transitions": transitions,
        "blank": blank,
    }


def check_determinism(tm):
    """Return a list of human-readable violation strings; empty list = deterministic."""
    groups = defaultdict(list)
    for t in tm["transitions"]:
        groups[(t["from"], t["read"])].append(t)

    violations = []
    for (state, symbol), group in groups.items():
        if len(group) > 1:
            dests = ", ".join(f"-> state {g['to']} (write '{g['write']}', move {g['move']})" for g in group)
            violations.append(
                f"state {state} has {len(group)} transitions reading '{symbol}': {dests}"
            )
    return violations


def _run(tm, input_string):
    """
    Shared simulation core. Runs a deterministic single-tape TM on
    input_string until it either halts (no applicable transition) or
    exceeds MAX_STEPS.

    Returns a dict: {
        "halted": bool,        # False if we hit MAX_STEPS (timeout)
        "final_state": bool,   # True if the machine halted *in* a final state
        "state": <state id at halt>,
        "tape": defaultdict mapping int position -> symbol,
        "head": <head position at halt>,
    }
    """
    blank = tm["blank"]
    tape = defaultdict(lambda: blank)
    for i, ch in enumerate(input_string):
        tape[i] = ch

    delta = {}
    for t in tm["transitions"]:
        delta[(t["from"], t["read"])] = t

    state = tm["initial"]
    head = 0
    steps = 0

    # A machine that starts in a final state halts immediately (0 steps).
    while True:
        if state in tm["finals"]:
            return {"halted": True, "final_state": True, "state": state, "tape": tape, "head": head}

        symbol = tape[head]
        key = (state, symbol)
        if key not in delta:
            return {"halted": True, "final_state": False, "state": state, "tape": tape, "head": head}

        if steps >= MAX_STEPS:
            return {"halted": False, "final_state": False, "state": state, "tape": tape, "head": head}

        t = delta[key]
        tape[head] = t["write"]
        if t["move"] == "R":
            head += 1
        elif t["move"] == "L":
            head -= 1
        state = t["to"]
        steps += 1


def simulate_decision(tm, input_string):
    """Returns "accept", "reject", or "timeout"."""
    result = _run(tm, input_string)
    if not result["halted"]:
        return "timeout"
    return "accept" if result["final_state"] else "reject"


def simulate_transducer(tm, input_string):
    """
    Returns (status, output) where status is "halted" or "timeout".
    On "halted", output is the tape contents starting at the head position
    at halt time, read to the right up to (not including) the first blank
    symbol. Accepting-state status is irrelevant for transducers -- any
    halt (including running out of applicable transitions) counts.
    """
    result = _run(tm, input_string)
    if not result["halted"]:
        return "timeout", None

    tape = result["tape"]
    blank = tm["blank"]
    head = result["head"]
    out_chars = []
    pos = head
    while tape[pos] != blank:
        out_chars.append(tape[pos])
        pos += 1
    return "halted", "".join(out_chars)


def load_lines(path):
    if not os.path.exists(path):
        raise TMParseError(f"test file not found: {path}")
    with open(path, "r") as f:
        lines = f.read().split("\n")
    if lines and lines[-1] == "":
        lines = lines[:-1]
    return lines


def grade_decision(jff_path, tests_path, points):
    tm = parse_tm(jff_path)
    violations = check_determinism(tm)
    if violations:
        return 0, ["Machine is NOT deterministic. No credit per assignment rules.",
                    "Conflicting transitions found:"] + [f"  - {v}" for v in violations]

    test_lines = load_lines(tests_path)
    if len(test_lines) != 20:
        note = [f"[WARN] Expected 20 test lines in {tests_path}, found {len(test_lines)}."]
    else:
        note = []

    expected = ["accept"] * 10 + ["reject"] * 10
    mismatches = []
    for i, s in enumerate(test_lines):
        want = expected[i] if i < len(expected) else None
        got = simulate_decision(tm, s)
        got_bucket = "accept" if got == "accept" else "reject"  # timeout counts as not-accept
        display_s = s if s != "" else "(empty string)"
        if want is not None and got_bucket != want:
            mismatches.append(
                f"line {i+1}: input {display_s!r} expected {want.upper()}, machine result: {got.upper()}"
            )

    if mismatches:
        return 0, note + [f"{len(mismatches)} of {len(test_lines)} test string(s) did not match:"] + \
                   [f"  - {m}" for m in mismatches]

    return points, note + [f"Deterministic and all {len(test_lines)} test strings correct."]


def grade_transducer(jff_path, tests_paths, points):
    inputs_path, outputs_path = tests_paths

    tm = parse_tm(jff_path)
    violations = check_determinism(tm)
    if violations:
        return 0, ["Machine is NOT deterministic. No credit per assignment rules.",
                    "Conflicting transitions found:"] + [f"  - {v}" for v in violations]

    inputs = load_lines(inputs_path)
    expected_outputs = load_lines(outputs_path)
    if len(inputs) != len(expected_outputs):
        return 0, [f"Test data error: {inputs_path} has {len(inputs)} line(s) but "
                    f"{outputs_path} has {len(expected_outputs)} line(s). These files "
                    f"must have the same number of lines, in matching order."]

    mismatches = []
    for i, (inp, expected_out) in enumerate(zip(inputs, expected_outputs), 1):
        status, got_out = simulate_transducer(tm, inp)
        display_in = inp if inp != "" else "(empty string)"
        display_exp = expected_out if expected_out != "" else "(empty string)"
        if status == "timeout":
            mismatches.append(
                f"line {i}: input {display_in} -> machine did not halt within {MAX_STEPS} steps "
                f"(expected output {display_exp})"
            )
        elif got_out != expected_out:
            display_got = got_out if got_out != "" else "(empty string)"
            mismatches.append(
                f"line {i}: input {display_in} -> expected output {display_exp}, "
                f"got {display_got}"
            )

    if mismatches:
        return 0, [f"{len(mismatches)} of {len(inputs)} test case(s) did not match:"] + \
                   [f"  - {m}" for m in mismatches]

    return points, [f"Deterministic and all {len(inputs)} test cases produced correct output."]


def grade_problem(label, jff_path, tests_path, kind, points):
    print(f"\n{'-'*60}")
    print(f"{label}  ({points} points)")
    print(f"{'-'*60}")

    try:
        if kind == "decision":
            score, messages = grade_decision(jff_path, tests_path, points)
        else:
            score, messages = grade_transducer(jff_path, tests_path, points)
    except TMParseError as e:
        score, messages = 0, [f"Could not parse/load: {e}"]

    tag = "PASS" if score == points else "FAIL"
    for m in messages:
        print(f"  {m}")
    print(f"  [{tag}] Score: {score} / {points}")
    return score


def read_username():
    path = "YOURUSERNAME.txt"
    if not os.path.exists(path):
        return "UNKNOWN (YOURUSERNAME.txt missing)"
    with open(path, "r") as f:
        first_line = f.readline().strip()
    if not first_line:
        return "UNKNOWN (YOURUSERNAME.txt is empty)"
    return first_line


def main():
    username = read_username()
    print("=" * 60)
    print("CSCE 355 Turing Machine Assignment - Grading Report")
    print(f"Username: {username}")
    print("=" * 60)

    total = 0
    for label, jff_name, tests_name, kind, points in PROBLEMS:
        total += grade_problem(label, jff_name, tests_name, kind, points)

    print(f"\n{'='*60}")
    print(f"USERNAME: {username}")
    print(f"TOTAL SCORE: {total} / {TOTAL_POSSIBLE}")
    print(f"{'='*60}")

    print(f"SCORE_LINE,{username},{total},{TOTAL_POSSIBLE}")


if __name__ == "__main__":
    main()
